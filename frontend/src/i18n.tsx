const COUNTRY_TO_LANG: Record<string, LangCode> = {
  Azerbaijan: 'AZ',
  'Türkiye': 'TR',
  Kazakhstan: 'KK',
  Kyrgyzstan: 'KY',
  Uzbekistan: 'UZ',
  Turkmenistan: 'TK',
};

export function countryToLang(country?: string | null): LangCode {
  if (!country) return 'AZ';
  return COUNTRY_TO_LANG[country] || inferLang(country) || 'AZ';
}

function inferLang(country: string): LangCode | undefined {
  const upper = country.toUpperCase();
  if (upper.startsWith('AZER')) return 'AZ';
  if (/TURK/.test(upper)) return 'TR';
  if (/KAZ|QAZ/.test(upper)) return 'KK';
  if (/KYRG|KIRG/.test(upper)) return 'KY';
  if (/UZB|OZBEK/.test(upper)) return 'UZ';
  if (/TURKM/.test(upper)) return 'TK';
  return undefined;
}

export function flagOf(country?: string | null): string {
  const c = UNION_COUNTRIES.find((x) => x.id === country);
  return c ? c.flag : countryToLang(country) === 'TR' ? '🇹🇷' : '🌍';
}

