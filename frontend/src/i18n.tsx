export const TRANSLATIONS: Record<LangCode, Record<string, string>> = {
  AZ,
  TR,
  KK,
  KY,
  UZ,
  TK,
  EN,
};

interface I18nContextValue {
  lang: LangCode;
  setLang: (lang: LangCode) => void;
  t: (key: string) => string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

export const I18nProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [lang, setLangState] = useState<LangCode>(() => {
    const stored = localStorage.getItem('th_lang');
    return (LANG_META.some((l) => l.code === stored) ? stored as LangCode : 'AZ');
  });

  const setLang = (code: LangCode) => {
    localStorage.setItem('th_lang', code);
    setLangState(code);
  };

  const t = (key: string) => {
    const dict = TRANSLATIONS[lang] || AZ;
    return dict[key] ?? AZ[key] ?? key;
  };

  return <I18nContext.Provider value={{ lang, setLang, t }}>{children}</I18nContext.Provider>;
};

export function useI18n(): I18nContextValue {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used within I18nProvider');
  return ctx;
}